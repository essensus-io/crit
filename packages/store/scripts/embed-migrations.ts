import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
export function renderMigrations(): string {
  const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8")) as {
    entries: { idx: number; tag: string }[];
  };
  const items = journal.entries
    .toSorted((a, b) => a.idx - b.idx)
    .map((e) => {
      const sql = readFileSync(join(root, "drizzle", `${e.tag}.sql`), "utf8");
      const statements = sql
        .split("--> statement-breakpoint")
        .map((s) => s.trim())
        .filter(Boolean);
      return { tag: e.tag, statements };
    });
  return `// Generated by scripts/embed-migrations.ts from drizzle/. Do not edit.\nexport const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(items, null, 2)};\n`;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(join(root, "src/db/migrations.gen.ts"), renderMigrations());
  console.log("wrote src/db/migrations.gen.ts");
}
